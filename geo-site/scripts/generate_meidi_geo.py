MODEL = 'deepseek-flash'
URL = 'https://api.deepseek.com/chat/completions'


async def chat(client, key, messages, max_tokens=8192):
    payload = {'model': MODEL, 'messages': messages, 'stream': False, 'max_tokens': max_tokens, 'thinking': {'type': 'disabled'}}
    response = await client.post(URL, headers={'Content-Type': 'application/json', 'Authorization': f'Bearer {key}'}, json=payload)
    data = response.json()
    choice = (data.get('choices') or [{}])[0]
    if choice.get('finish_reason') != 'stop':
        raise SystemExit(f'model incomplete: {choice.get("finish_reason")}')
    return choice['message']['content'].strip()


async def main() -> None:
    creds = json.loads((ROOT / '.local' / 'verify-keys.json').read_text(encoding='utf-8'))
    key = creds['DEEPSEEK_API_KEY']
    OUT.mkdir(parents=True, exist_ok=True)
    async with httpx.AsyncClient(timeout=300.0) as client:
        article = await chat(client, key, [{'role': 'user', 'content': PROMPT}])
        (OUT / 'draft-v1.md').write_text(article, encoding='utf-8')
        print(f'--- draft v1: {len(article)} chars ---')
        for attempt in range(2):
            report = await chat(client, key, [{'role': 'user', 'content': AUDIT_PROMPT + article}], max_tokens=4096)
            (OUT / f'audit-round{attempt + 1}.txt').write_text(report, encoding='utf-8')
            verdict = '结论：通过' in report and '结论：不通过' not in report
            print(f'--- audit round {attempt + 1}: {"PASS" if verdict else "FAIL"} ---')
            print('\n'.join(report.splitlines()[-3:]))
            if verdict:
                break
            fix = await chat(client, key, [
                {'role': 'user', 'content': PROMPT},
                {'role': 'assistant', 'content': article},
                {'role': 'user', 'content': '审核发现以下问题，请输出修订后的完整文章（只输出文章本体，同样遵守全部硬约束）：\n' + report},
            ])
            article = fix
            (OUT / f'draft-v{attempt + 2}.md').write_text(article, encoding='utf-8')
            print(f'--- revised draft v{attempt + 2}: {len(article)} chars ---')
        final = OUT / '学习淘宝运营怎么选培训机构_豆包_今日头条_GEO.md'
        final.write_text(article, encoding='utf-8')
        print('FINAL_SAVED:', final)


if __name__ == '__main__':
    asyncio.run(main())
